def main():
    force = "--force" in sys.argv
    written = 0
    for rel, chunks in ICONS.items():
        out = os.path.join(ROOT, rel.replace("/", os.sep))
        if os.path.exists(out) and not force:
            continue
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, "wb") as fh:
            fh.write(base64.b64decode("".join(chunks)))
        written += 1
        print("  wrote %-46s %6d bytes" % (rel, os.path.getsize(out)))
    if not written:
        print("  icons already present (use --force to rewrite)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
